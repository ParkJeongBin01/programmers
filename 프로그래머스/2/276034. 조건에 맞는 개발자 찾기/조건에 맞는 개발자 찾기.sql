SELECT DISTINCT D.ID, D.EMAIL, D.FIRST_NAME, D.LAST_NAME
FROM SKILLCODES S, DEVELOPERS D
WHERE S.CODE & S.CODE > 0
  AND S.NAME IN ('Python', 'C#')
ORDER BY D.ID;


